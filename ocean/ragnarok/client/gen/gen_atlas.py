#!/usr/bin/env python3
"""Write ../rathena_atlas.h: the travel region's maps, where they lie, and the warps between them.

Usage: python3 gen_atlas.py [rathena_dir] [pre-re|re] [map ...]
The rules default to those the checkout was configured with (as gen_mobs.py reads them). The maps
default to RG_TRAVEL_MAPS in ../../slurm/world.sh. Warps come from rAthena's npc/<rules>/warps
(fields and cities); only those between two maps of the region are kept, as the lean training
worlds load them. Each map gets a place on a grid of map-sized squares: the first map is (0, 0), and
a warp at a map's west, east, south or north edge puts the map it leads to one square that way. A
point's world position is then (gx * RO_ATLAS_SQUARE + x, gy * RO_ATLAS_SQUARE + y), which is what
the travel task's compass measures. Map sizes come from rAthena's map caches.
"""
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RA = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "ragnarok/rathena-re")
MAKEFILE = RA / "src/map/Makefile"
BUILT = ("pre-re" if "-DPRERE" in MAKEFILE.read_text() else "re") if MAKEFILE.exists() else None
RULES = sys.argv[2] if len(sys.argv) > 2 else BUILT or "pre-re"
if RULES not in ("pre-re", "re"):
    sys.exit(f"rules must be pre-re or re, not {RULES}")
MAPS = sys.argv[3:] or re.search(r'RG_TRAVEL_MAPS="([^"]*)"', (HERE / "../../slurm/world.sh").read_text())[1].split()
OUT = HERE.parent / "rathena_atlas.h"
SQUARE = 400  # cells per grid square, about a field's size
EDGE = 40     # a warp this close to a map's side leads that way


def map_sizes():
    # As the map server and the client read them: db/import/, then db/<rules>/, then db/ itself.
    sizes = {}
    for sub in ("", f"{RULES}/", "import/"):
        path = RA / f"db/{sub}map_cache.dat"
        if not path.exists():
            continue
        data = path.read_bytes()
        count, off = struct.unpack_from("<H", data, 4)[0], 8
        for _ in range(count):
            name = data[off:off + 12].split(b"\0")[0].decode()
            xs, ys, length = struct.unpack_from("<hhi", data, off + 12)
            sizes[name] = (xs, ys)
            off += 20 + length
    return sizes


sizes = map_sizes()
missing = [m for m in MAPS if m not in sizes]
if missing:
    sys.exit(f"not in the map cache: {missing}")
warps = []  # (from, x, y, span x, span y, to, tx, ty)
for path in sorted((RA / f"npc/{RULES}/warps").glob("*/*.txt")):
    for line in path.read_text(errors="replace").splitlines():
        parts = line.split("\t")
        if line.startswith("//") or len(parts) < 4 or parts[1].strip() != "warp":
            continue
        src = parts[0].split(",")
        spec = parts[3].split(",")
        if src[0] in MAPS and spec[2] in MAPS and src[0] != spec[2]:
            warps.append((src[0], int(src[1]), int(src[2]), int(spec[0]), int(spec[1]), spec[2], int(spec[3]),
                          int(spec[4])))

grid = {MAPS[0]: (0, 0)}
changed = True
while changed:
    changed = False
    for m, x, y, _, _, to, _, _ in warps:
        if m not in grid or to in grid:
            continue
        xs, ys = sizes[m]
        gx, gy = grid[m]
        if x < EDGE:
            gx -= 1
        elif x >= xs - EDGE:
            gx += 1
        elif y < EDGE:
            gy -= 1
        elif y >= ys - EDGE:
            gy += 1
        grid[to] = (gx, gy)
        changed = True
unplaced = [m for m in MAPS if m not in grid]
if unplaced:
    sys.exit(f"no warp path from {MAPS[0]} to {unplaced}")

with OUT.open("w") as f:
    f.write(f"// Generated by gen/gen_atlas.py from {RA.name}/npc/{RULES}/warps. Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define RO_ATLAS_SQUARE {SQUARE}  // cells per grid square\n")
    f.write(f"#define RO_ATLAS_MAPS {len(MAPS)}\n#define RO_ATLAS_WARPS {len(warps)}\n\n")
    f.write("// A map: its name, grid square and size.\n")
    f.write("typedef struct RoAtlasMap { const char* name; int16_t gx, gy, xs, ys; } RoAtlasMap;\n")
    f.write("// A warp: the cells within (sx, sy) of (x, y) on map `from` lead to (tx, ty) on map `to` "
            "(map indices).\n")
    f.write("typedef struct RoAtlasWarp { uint8_t from, to; int16_t x, y, sx, sy, tx, ty; } RoAtlasWarp;\n\n")
    f.write("static const RoAtlasMap RO_ATLAS_MAP[RO_ATLAS_MAPS] = {\n")
    for m in MAPS:
        f.write(f'    {{"{m}", {grid[m][0]}, {grid[m][1]}, {sizes[m][0]}, {sizes[m][1]}}},\n')
    f.write("};\n\nstatic const RoAtlasWarp RO_ATLAS_WARP[RO_ATLAS_WARPS] = {\n")
    for m, x, y, sx, sy, to, tx, ty in warps:
        f.write(f"    {{{MAPS.index(m)}, {MAPS.index(to)}, {x}, {y}, {sx}, {sy}, {tx}, {ty}}},  // {m} -> {to}\n")
    f.write("};\n")
print(f"wrote {OUT}: {len(MAPS)} maps, {len(warps)} warps; grid " +
      ", ".join(f"{m} {grid[m]}" for m in MAPS))
