#!/usr/bin/env python3
"""Write ../rathena_mobs.h: per-monster properties from rAthena's mob_db, for observations.

Usage: python3 gen_mobs.py [rathena_dir] [pre-re|re] [out.h]
The rules default to those the checkout was configured with (-DPRERE in its src/map/Makefile, as
gen_packets.py reads them), else pre-renewal; they pick db/pre-re/mob_db.yml or db/re/mob_db.yml.
Each row: id, level, max HP, attack, defense, element (0..9), aggressive (rAthena AI types that attack
on sight), boss. The env describes monsters by these, not by id, so a policy can meet new ones.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RA = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "ragnarok/rathena-train")
MAKEFILE = RA / "src/map/Makefile"
BUILT = ("pre-re" if "-DPRERE" in MAKEFILE.read_text() else "re") if MAKEFILE.exists() else None
RULES = sys.argv[2] if len(sys.argv) > 2 else BUILT or "pre-re"
if RULES not in ("pre-re", "re"):
    sys.exit(f"rules must be pre-re or re, not {RULES}")
OUT = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE.parent / "rathena_mobs.h"
ELEMENTS = ["Neutral", "Water", "Earth", "Fire", "Wind", "Poison", "Holy", "Dark", "Ghost", "Undead"]
# rAthena mob AI types (doc/mob_db_mode_list.txt) whose monsters attack on sight.
AGGRESSIVE = {"04", "05", "08", "09", "10", "13", "19", "20", "21", "24", "25", "26", "27"}

rows = []
for item in re.split(r"\n  - Id: ", (RA / f"db/{RULES}/mob_db.yml").read_text())[1:]:
    mid = int(item.split("\n", 1)[0].strip())
    g = lambda k: (re.search(r"\n    " + k + r": (.*)", item) or [None, ""])[1].strip()
    level, hp = int(g("Level") or 1), int(g("Hp") or 1)
    attack, defense = int(g("Attack") or 0), int(g("Defense") or 0)
    element = ELEMENTS.index(g("Element")) if g("Element") in ELEMENTS else 0
    boss = int(g("Class") == "Boss" or "Mvp" in item.split("\n    Drops:")[0] and "MvpExp" in item)
    rows.append((mid, level, hp, attack, defense, element, int(g("Ai") in AGGRESSIVE), boss))

with OUT.open("w") as f:
    f.write(f"// Generated by gen/gen_mobs.py from {RA.name}/db/{RULES}/mob_db.yml. Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    # 32-bit attack and defense: some renewal monsters have more than 32767 (Satan Morroc's 42597).
    f.write("typedef struct RoMobInfo { uint16_t id, level; int32_t hp, attack, defense; "
            "uint8_t element, aggressive, boss; } RoMobInfo;\n\n")
    f.write("// element: 0 Neutral, 1 Water, 2 Earth, 3 Fire, 4 Wind, 5 Poison, 6 Holy, 7 Dark, 8 Ghost, 9 Undead\n")
    f.write(f"static const RoMobInfo RO_MOBS[{len(rows)}] = {{\n")
    for r in rows:
        f.write("    {%d, %d, %d, %d, %d, %d, %d, %d},\n" % r)
    f.write("};\n\n")
    f.write("static inline const RoMobInfo* ro_mob_info(int id) {\n"
            f"    int lo = 0, hi = {len(rows)} - 1;\n"
            "    while (lo <= hi) {\n        int mid = (lo + hi) / 2;\n"
            "        if (RO_MOBS[mid].id == id) return &RO_MOBS[mid];\n"
            "        if (RO_MOBS[mid].id < id) lo = mid + 1; else hi = mid - 1;\n    }\n    return 0;\n}\n")
print(f"{len(rows)} monsters from db/{RULES} -> {OUT.name}")
